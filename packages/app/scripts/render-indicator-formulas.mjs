#!/usr/bin/env node
// Renders every indicator formula in the shared catalog to MathML at build time.
// Runtime ships zero KaTeX: the component only reads the generated record.
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";

import { renderToString } from "katex";

import { tokenize } from "../src/features/chart/utils/formula-utils.ts";

const APP_ROOT = path.resolve(import.meta.dirname, "..");
const OUTPUT = path.join(APP_ROOT, "src/features/chart/generated/indicator-formulas.generated.ts");
const HEADER = "// Generated by scripts/render-indicator-formulas.mjs — do not edit.";

// Node's type stripping resolves exact file names; the workspace sources import
// extensionless (`./catalog/trend`), so append the TypeScript extension.
if (typeof Bun === "undefined") {
  const { registerHooks } = await import("node:module");
  registerHooks({
    resolve(specifier, context, nextResolve) {
      if (specifier.startsWith(".") && path.extname(specifier) === "") {
        for (const suffix of [".ts", "/index.ts"]) {
          try {
            return nextResolve(specifier + suffix, context);
          } catch {
            // try the next candidate
          }
        }
      }
      return nextResolve(specifier, context);
    },
  });
}

async function loadCatalog() {
  const module = await import("@0xsignal/shared/indicators/config.ts");
  return module.AVAILABLE_INDICATORS;
}

function renderToken(token) {
  try {
    return renderToString(String(token), {
      output: "mathml",
      displayMode: true,
      throwOnError: false,
    });
  } catch (error) {
    throw new Error(`Failed to render token: ${token}`, { cause: error });
  }
}

export async function buildArtifact() {
  const indicators = await loadCatalog();
  const formulas = [
    ...new Set(
      indicators
        .map((indicator) => indicator.usage?.formula)
        .filter((formula) => typeof formula === "string" && formula.trim() !== ""),
    ),
  ];
  const tokens = [...new Set(formulas.flatMap((formula) => tokenize(formula)))].toSorted();

  const entries = tokens.map((token) => [token, renderToken(token)]);
  const body = entries.map(
    ([token, html]) => `  ${JSON.stringify(token)}: ${JSON.stringify(html)},`,
  );
  const output = [
    HEADER,
    "export const INDICATOR_FORMULA_MATHML: Record<string, string> = {",
    ...body,
    "};",
    "",
  ].join("\n");

  return { output, tokenCount: tokens.length, formulaCount: formulas.length };
}

const isMain =
  process.argv[1] !== undefined &&
  import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href;

if (isMain) {
  try {
    const { output, tokenCount, formulaCount } = await buildArtifact();
    await mkdir(path.dirname(OUTPUT), { recursive: true });
    await writeFile(OUTPUT, output);
    console.log(
      `Generated ${tokenCount} tokens for ${formulaCount} formulas, ${Buffer.byteLength(output)} bytes`,
    );
  } catch (error) {
    console.error(error);
    process.exit(1);
  }
}
